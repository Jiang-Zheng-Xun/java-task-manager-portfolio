-- BTRIM only removes ASCII spaces; it is intentionally weaker than the Java
-- Character.isWhitespace/isSpaceChar rule enforced by EvidenceContent.
CREATE TABLE task_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    content VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_task_evidence_task
        FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE,

    CONSTRAINT chk_task_evidence_content_not_blank
        CHECK (BTRIM(content) <> '')
);

CREATE INDEX idx_task_evidence_task_created_id
    ON task_evidence (task_id, created_at DESC, id DESC);
